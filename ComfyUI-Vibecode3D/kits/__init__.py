"""Game kits beyond Pong. A kit is a module with:

  KIT       its name, the folder under LIB_COMFY/parts ("cbrick")
  PREFIX    the handler prefix its parts use ("Brick"); the config handler is PREFIX.Config
  TITLE     the genre in words, for the header
  fixups(g)        -> g: a copy made playable whatever the chain said (notes say what was added)
  parts_needed(g)  -> ["common/vec", "core", ...]: part files, "dir/name" for another folder
  config(g)        -> [(xTalk variable, value)]: what PREFIX.Config puts where
  rules_lines(g)   -> header lines (CONTROLS, RULES) for the game launcher
  preview(g, d, P) draws a still frame with PIL (d an ImageDraw, P(x, y) a screen point)

Pong (cpong) stays in assemble.py as it was; build() there sends every other kit here.
"""
import os
import re

from . import brick, coil, dodge, lander, rocks, wave  # noqa: E402

KITS = {m.KIT: m for m in (brick, wave, coil, dodge, lander, rocks)}


def use_kit(game, kit):
    """A kit's node says which kit the chain builds. Pong nodes (Court, Paddle) before it are
    noted and left out; the shared ones (Palette, Ball, Arena) carry over."""
    if game["kit"] != kit:
        if game["kit"] != "cpong" or game.get("court") or game.get("paddles"):
            game["notes"].append("%s nodes after %s ones: building %s" % (kit, game["kit"], kit))
        game["kit"] = kit
    game.setdefault("k", {})
    return game


def rgb(c):
    return "%d,%d,%d" % tuple(c)


def q(s):
    return '"' + str(s).replace('"', "'") + '"'


def hud_safe(s):
    """HUD letters: A-Z 0-9 : - + . ! / ^ ? , ' and space"""
    return re.sub(r"[^A-Z0-9:\-+.!/^?,' ]", " ", str(s).upper())


def value(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (tuple, list)) and len(v) == 3 and all(isinstance(x, int) for x in v):
        return q(rgb(v))
    if isinstance(v, (int, float)):
        return repr(round(v, 4)) if isinstance(v, float) else str(v)
    return q(v)


def config_handler(prefix, items, clears):
    L = ["on %s.Config" % prefix]
    for var in clears:
        L.append("   put empty into %s" % var)
    for var, v in items:
        L.append("   put %s into %s" % (value(v), var))
    L.append("end %s.Config" % prefix)
    return "\n".join(L)


def header(kit, g, name, parts):
    return "\n".join(["#" * 86,
                      '## CARD SCRIPT: "Play.%s"   %s  (made in ComfyUI, seed %s)' % (name, hud_safe(g["title"]), g["seed"]),
                      "## A %s put together by the Vibecode3D nodes from LIB_COMFY/parts: %s." % (kit.TITLE, ", ".join(parts))]
                     + ["## " + line for line in kit.rules_lines(g)] + ["#" * 86, ""])


def build(game, projects_root, out_dir, name):
    kit = KITS[game["kit"]]
    g = kit.fixups(game)
    parts = kit.parts_needed(g)
    chunks = [header(kit, g, name, parts)]
    for part in parts:
        folder, _, pname = part.rpartition("/")
        path = os.path.join(projects_root, "LIB_COMFY", "parts", folder or kit.KIT, pname + ".part.livecodescript")
        with open(path, encoding="utf-8") as f:
            chunks.append(f.read().rstrip() + "\n")
    items, clears = kit.config(g)
    chunks.append("## PART config (generated by the Build node)\n" + config_handler(kit.PREFIX, items, clears) + "\n")
    script = "\n".join(chunks)
    if out_dir is None:
        out_dir = os.path.join(projects_root, "LIB_GAMES", "Vibecode3D_Games")
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "Vibecode3D_Play_%s.livecodescript" % name)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(script)
    g["parts"] = parts
    g["file_name"] = name
    return path, script, g


# ------------------------------------------------------------ shared node settings
def arena_or_default(g, hw=360, hh=210, floor="grid", grid=60):
    """the Arena node's settings, or a default arena (noted)"""
    a = g.get("arena")
    if a is None:
        from .. import assemble
        if g["palette"] is None:
            assemble.palette(g, 190, "neon", 1.0)
        a = {"hw": hw, "hh": hh, "cy": 40, "floor": floor, "grid": grid,
             "wall": g["palette"]["wall"]}
        g["notes"].append("no Arena node: a %dx%d %s arena was used" % (hw * 2, hh * 2, floor))
    a = dict(a)
    a["deco"] = tuple(int(v * 0.4) for v in a["wall"])
    return a


def arena_config(a):
    return [('sCfg["hw"]', a["hw"]), ('sCfg["hh"]', a["hh"]), ('sCfg["cy"]', a["cy"]),
            ('sCfg["floor"]', a["floor"]), ('sCfg["grid"]', a["grid"]),
            ('sCfg["wallColor"]', a["wall"]), ('sCfg["decoColor"]', a["deco"])]


def keys_words(ctrl, fire=None):
    move = {"arrows": "ARROWS MOVE", "wasd": "W A S D MOVE", "mouse": "THE MOUSE MOVES"}.get(ctrl, "ARROWS MOVE")
    if fire:
        move += "  " + fire
    return move


def palette_role(g, role):
    from .. import assemble
    if g["palette"] is None:
        assemble.palette(g, 190, "neon", 1.0)
    return g["palette"][role]


def shade(c, f):
    return tuple(max(0, min(255, int(v * f))) for v in c)


def ramp(a, b, n):
    """n colours from a to b"""
    if n <= 1:
        return [tuple(a)]
    return [tuple(int(a[i] + (b[i] - a[i]) * k / (n - 1)) for i in range(3)) for k in range(n)]
